from __future__ import annotations

import logging

from pydantic import ValidationError

from app.common.exceptions import BusinessException
from app.core.ai.dispatcher import AIDispatcher
from app.core.ai.exceptions import AIResponseError
from app.modules.dynamic_report.schemas import DynamicReportIntent


logger = logging.getLogger(__name__)


class DynamicReportIntentParser:
    def __init__(self) -> None:
        self.ai_dispatcher = AIDispatcher()

    def parse(self, prompt: str) -> DynamicReportIntent:
        ai_prompt = self._build_prompt(prompt)
        try:
            result = self.ai_dispatcher.generate_json(ai_prompt)
        except AIResponseError as exc:
            raise BusinessException(
                "No se pudo analizar tu solicitud de reporte en este momento."
            ) from exc

        try:
            intent = DynamicReportIntent.model_validate(result.content)
        except ValidationError as exc:
            raise BusinessException(
                "Invalid report intent generated by AI."
            ) from exc

        logger.info(
            "Dynamic report intent parsed. report_type=%s title=%s metrics=%s dimensions=%s filters=%s sort=%s limit=%s output=%s",
            intent.report_type,
            intent.title,
            intent.metrics,
            intent.dimensions,
            intent.filters,
            [
                {
                    "field": sort.field,
                    "direction": sort.direction,
                }
                for sort in intent.sort
            ],
            intent.limit,
            intent.output,
        )

        return intent

    def _build_prompt(self, prompt: str) -> str:
        return f"""
You are an AI report intent parser.

Convert the user request into JSON.

JSON contract:

{{
  "report_type": "INCIDENTS",
  "title": "Title",
  "description": null,
  "metrics": [],
  "dimensions": [],
  "filters": {{}},
  "sort": [],
  "limit": null,
  "output": "TABLE"
}}

Rules:

- Return only valid JSON.
- Never generate SQL.
- Never invent IDs.
- Use provider_name when company names appear.
- Use status COMPLETED for attended incidents.
- Use status REJECTED for rejected incidents.
- Use status CANCELLED for cancelled incidents.

User prompt:

{prompt}
""".strip()
